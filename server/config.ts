import type { BackendMode } from '../shared/types';
import { ConfigError } from './errors';

export interface ServerConfig {
  mode: BackendMode;
  publicBaseUrl: string | null;
  timezone: string;
  /** Passwordless local test sign-in is enabled (local development only). */
  devStaffLogin: boolean;
  /** Test sign-in emails that act as normal staff (borrowers). */
  devStaffEmails: string[];
  /** Test sign-in emails that act as admin. */
  devAdminEmails: string[];
  /** `npm run dev:lan`: also accept the test sign-in from private-network devices (with the passcode). */
  devLanLogin: boolean;
  /** Passcode those devices must send. Generated by the dev server at start-up unless DEV_LAN_PASSCODE is set. */
  devLanPasscode: string | null;
}

/**
 * Memory mode keeps data in the dev server's RAM. It is only allowed when running
 * locally (our Vite dev server, `netlify dev`) or in automated tests, so a deployed
 * site can never silently run without a real database.
 */
export function isLocalDevelopment(): boolean {
  const env = process.env;
  // Deployed Netlify Functions run on AWS Lambda: never treat that as local, whatever else is set.
  if (env.AWS_LAMBDA_FUNCTION_NAME || (env.NETLIFY === 'true' && env.NETLIFY_DEV !== 'true')) return false;
  return env.RM_LOCAL_DEV === '1' || env.NETLIFY_DEV === 'true' || env.NODE_ENV === 'test' || !!env.VITEST;
}

export function getConfig(): ServerConfig {
  const env = process.env;
  const rawMode = (env.BACKEND_MODE ?? 'firebase').trim().toLowerCase();
  if (rawMode !== 'firebase' && rawMode !== 'memory') {
    throw new ConfigError('BACKEND_MODE must be "firebase" or "memory".');
  }
  const mode = rawMode as BackendMode;
  if (mode === 'memory' && !isLocalDevelopment()) {
    throw new ConfigError(
      'BACKEND_MODE=memory is only allowed for local development. Set BACKEND_MODE=firebase on deployed sites.',
    );
  }

  let publicBaseUrl: string | null = null;
  const rawBase = env.PUBLIC_BASE_URL?.trim();
  if (rawBase) {
    let parsed: URL;
    try {
      parsed = new URL(rawBase);
    } catch {
      throw new ConfigError('PUBLIC_BASE_URL is not a valid URL (example: https://your-site.netlify.app).');
    }
    if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
      throw new ConfigError('PUBLIC_BASE_URL must start with https:// or http://');
    }
    publicBaseUrl = parsed.origin + parsed.pathname.replace(/\/+$/, '');
    // A deployed site must never print localhost into QR codes: ignore it there, so the app falls back to
    // the address people actually opened (window.location.origin).
    if (!isLocalDevelopment() && /^(localhost|127\.0\.0\.1|\[::1\])$/.test(parsed.hostname)) publicBaseUrl = null;
  }

  const timezone = env.APP_TIMEZONE?.trim() || 'UTC';
  try {
    new Intl.DateTimeFormat('en-CA', { timeZone: timezone });
  } catch {
    throw new ConfigError('APP_TIMEZONE is not a valid IANA time zone (example: Asia/Singapore).');
  }

  // Local staff test sign-in (no password). Always on in memory mode; opt-in with DEV_STAFF_LOGIN=true
  // in firebase mode. Never allowed on a deployed site — the server refuses to start instead.
  const devLoginRequested = (env.DEV_STAFF_LOGIN ?? '').trim().toLowerCase() === 'true';
  if (devLoginRequested && !isLocalDevelopment()) {
    throw new ConfigError('DEV_STAFF_LOGIN=true is only allowed on your own computer. Remove it from the deployed site settings.');
  }
  const devStaffLogin = mode === 'memory' || devLoginRequested;
  const list = (raw: string | undefined, fallback: string) =>
    devStaffLogin
      ? (raw ?? fallback)
          .split(',')
          .map((s) => s.trim().toLowerCase())
          .filter(Boolean)
      : [];
  const devAdminEmails = list(env.DEV_ADMIN_EMAILS, 'dev.admin@example.test');
  const devStaffEmails = list(env.DEV_STAFF_EMAILS, 'dev.staff@example.test').filter((e) => !devAdminEmails.includes(e));


  // RM_DEV_LAN is set only by `npm run dev:lan` (Vite mode "lan"). Never on a deployed site.
  const devLanLogin = devStaffLogin && env.RM_DEV_LAN === '1' && isLocalDevelopment();
  let devLanPasscode: string | null = null;
  if (devLanLogin) {
    devLanPasscode = (env.DEV_LAN_PASSCODE ?? '').replace(/[\s-]/g, '').toUpperCase() || null;
    if (!devLanPasscode || devLanPasscode.length < 8) {
      throw new ConfigError('DEV_LAN_PASSCODE must be at least 8 characters (or leave it unset to get a random one).');
    }
  }

  return {
    mode,
    publicBaseUrl,
    timezone,
    devStaffLogin,
    devStaffEmails,
    devAdminEmails,
    devLanLogin,
    devLanPasscode,
  };
}
